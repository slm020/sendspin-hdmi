#!/usr/bin/env python3
"""Start the HDMI kiosk: sway (Wayland) + Chromium full screen on the now-playing page."""
import os
import shlex
import shutil
import signal
import subprocess
import sys
import time
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import config as conf  # noqa: E402

RUN = "/run/sendspin-hdmi"


def main():
    cfg = conf.load()
    if not cfg["screen"]["enabled"]:
        print("screen disabled in settings; not starting the kiosk", flush=True)
        return 0
    port = int(cfg["web"]["port"])
    url = f"http://127.0.0.1:{port}/"
    for _ in range(60):  # wait for the web service
        try:
            urllib.request.urlopen(url + "api/screen", timeout=2)
            break
        except Exception:
            time.sleep(1)
    chromium = shutil.which("chromium") or shutil.which("chromium-browser") or "chromium"
    profile = os.path.join(conf.STATE_DIR, "kiosk-profile")
    os.makedirs(RUN, exist_ok=True)
    os.makedirs(os.path.join(RUN, "xdg"), mode=0o700, exist_ok=True)
    # Browser launcher script: sway's "exec" splits commands on commas, so flags like
    # --disable-features=A,B must not be written into the sway config directly.
    browser = os.path.join(RUN, "browser.sh")
    flags = ["--no-sandbox", "--kiosk", "--ozone-platform=wayland", "--noerrdialogs", "--disable-infobars",
             "--no-first-run", "--disable-translate", "--disable-features=Translate,MediaRouter",
             "--password-store=basic", "--check-for-update-interval=31536000",
             f"--user-data-dir={profile}", url]
    # Only this kiosk uses the profile: clear stale locks (e.g. left after a hostname change,
    # which makes Chromium think another computer owns the profile and refuse to start).
    for name in ("SingletonLock", "SingletonSocket", "SingletonCookie"):
        try:
            os.unlink(os.path.join(profile, name))
        except FileNotFoundError:
            pass
    cmd = " ".join(shlex.quote(a) for a in [chromium, *flags])
    with open(browser, "w") as f:
        # keep the browser running: if it ever exits, start it again
        f.write("#!/bin/sh\n# generated by sendspin-hdmi kiosk.py\nwhile true; do\n"
                f"  rm -f {shlex.quote(profile)}/Singleton*\n  {cmd}\n  sleep 3\ndone\n")
    os.chmod(browser, 0o755)
    sway_conf = os.path.join(RUN, "sway.conf")
    with open(sway_conf, "w") as f:
        f.write(f"""# generated by sendspin-hdmi kiosk.py
output * mode {cfg['screen']['resolution']}
output * bg #000000 solid_color
default_border none
focus_follows_mouse no
seat * hide_cursor 1
exec {browser}
""")
    xdg = os.path.join(RUN, "xdg")
    for name in os.listdir(xdg):  # leftovers from a killed sway
        if name.startswith(("wayland-", "sway-ipc.")):
            try:
                os.unlink(os.path.join(xdg, name))
            except OSError:
                pass
    env = dict(os.environ, XDG_RUNTIME_DIR=xdg, LIBSEAT_BACKEND="noop",
               WLR_BACKENDS="drm", WLR_RENDERER=os.environ.get("WLR_RENDERER", "gles2"), HOME="/root")
    # Atomic KMS commits on Intel HDMI can fail with EBUSY when the receiver/projector
    # renegotiates; wlroots then never schedules another frame and the picture freezes.
    # The legacy KMS path doesn't hit this. Set WLR_DRM_NO_ATOMIC=0 in the unit to undo.
    env.setdefault("WLR_DRM_NO_ATOMIC", "1")
    sway = shutil.which("sway") or "/usr/bin/sway"
    proc = subprocess.Popen([sway, "--unsupported-gpu", "-c", sway_conf], env=env)

    def stop(*_):
        proc.terminate()
        sys.exit(0)
    signal.signal(signal.SIGTERM, stop)
    return watchdog(proc, xdg)


def watchdog(proc, xdg):
    """Restart the screen if sway stops producing frames.

    Every 20 s ask sway for a tiny screenshot. A healthy sway answers within a frame;
    a frozen one (stuck output) never does. Two misses in a row -> stop sway and exit
    non-zero so systemd starts the kiosk again.
    """
    grim = shutil.which("grim")
    misses = 0
    time.sleep(30)  # let sway and the browser start
    while proc.poll() is None:
        sock = next((n for n in sorted(os.listdir(xdg))
                     if n.startswith("wayland-") and not n.endswith(".lock")), None)
        if grim and sock:
            env = dict(os.environ, XDG_RUNTIME_DIR=xdg, WAYLAND_DISPLAY=sock)
            try:
                subprocess.run([grim, "-s", "0.05", "-t", "ppm", "-"], env=env, timeout=10,
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
                misses = 0
            except (subprocess.TimeoutExpired, subprocess.CalledProcessError):
                misses += 1
                print(f"screen watchdog: sway did not deliver a frame ({misses})", flush=True)
                if misses >= 2:
                    print("screen watchdog: screen frozen, restarting it", flush=True)
                    proc.terminate()
                    try:
                        proc.wait(10)
                    except subprocess.TimeoutExpired:
                        proc.kill()
                    return 1
        time.sleep(20)
    return proc.returncode or 1


if __name__ == "__main__":
    sys.exit(main())
